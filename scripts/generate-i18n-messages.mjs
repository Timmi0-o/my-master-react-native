import {
	mkdirSync,
	readdirSync,
	readFileSync,
	statSync,
	watch,
	writeFileSync,
} from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const MESSAGES_DIR = path.join(ROOT, 'messages')

const OUT_FILE = path.join(
	ROOT,
	'configs',
	'i18n',
	'generated',
	'locale-resources.generated.ts',
)

const IMPORT_PREFIX = '../../../messages'
const I18N_NAMESPACES = ['common', 'pages', 'ui']

function collectJsonFiles(dir, base = '') {
	const files = []

	for (const entry of readdirSync(dir).sort()) {
		const abs = path.join(dir, entry)
		const rel = base ? `${base}/${entry}` : entry

		if (statSync(abs).isDirectory()) {
			files.push(...collectJsonFiles(abs, rel))
		} else if (entry.endsWith('.json')) {
			files.push(rel)
		}
	}

	return files
}

function getLocales() {
	return readdirSync(MESSAGES_DIR)
		.filter((entry) => statSync(path.join(MESSAGES_DIR, entry)).isDirectory())
		.sort()
}

function toIdentifier(locale, relPath) {
	return `${locale}_${relPath}`.replace(/[^a-zA-Z0-9]/g, '_')
}

function generate() {
	const locales = getLocales()

	if (locales.length === 0) {
		throw new Error(`No locale folders found in ${MESSAGES_DIR}`)
	}

	const importLines = []
	const localeBlocks = []

	for (const locale of locales) {
		const files = collectJsonFiles(path.join(MESSAGES_DIR, locale))
		const wrappedParts = []
		const actionErrorParts = []
		const errorParts = []

		for (const relPath of files) {
			const id = toIdentifier(locale, relPath)
			importLines.push(
				`import ${id} from '${IMPORT_PREFIX}/${locale}/${relPath}'`,
			)

			const segments = relPath.replace(/\.json$/, '').split('/')
			const root = segments[0]

			if (root === 'action-errors') {
				actionErrorParts.push(
					`buildActionErrorsPart(${JSON.stringify(segments.slice(1))}, ${id})`,
				)
				continue
			}

			if (root === 'errors') {
				errorParts.push(`wrap(${JSON.stringify(segments)}, ${id})`)
				continue
			}

			if (root === 'stores') {
				continue
			}

			wrappedParts.push(`wrap(${JSON.stringify(segments)}, ${id})`)
		}

		const namespaceEntries = I18N_NAMESPACES.map((namespace) => {
			const mergeArgs = [
				`pickNamespace(mergeAll([\n\t\t\t${wrappedParts.join(',\n\t\t\t')},\n\t\t]), '${namespace}')`,
			]

			if (namespace === 'common') {
				mergeArgs.push(...actionErrorParts, ...errorParts)
			}

			return `\t\t${namespace}: mergeAll([\n\t\t\t${mergeArgs.join(',\n\t\t\t')},\n\t\t]),`
		})

		localeBlocks.push(`\t${locale}: {\n${namespaceEntries.join('\n')}\n\t},`)
	}

	const content = `// AUTO-GENERATED by scripts/generate-i18n-messages.mjs.
// Не редактировать вручную. Запуск: npm run i18n:gen
import { mergeMessages } from '../merge-messages'

${importLines.join('\n')}

type Messages = Record<string, unknown>

const wrap = (segments: string[], value: unknown): Messages =>
	segments.reduceRight<Messages>((acc, key) => ({ [key]: acc }), value as Messages)

const mergeAll = (parts: Messages[]): Messages =>
	parts.reduce<Messages>((acc, part) => mergeMessages(acc, part), {})

const pickNamespace = (tree: Messages, namespace: string): Messages => {
	const value = tree[namespace]
	return value && typeof value === 'object' ? (value as Messages) : {}
}

const kebabToCamel = (value: string): string =>
	value.replace(/-([a-z])/g, (_, char: string) => char.toUpperCase())

const ACTION_ERROR_KEY_MAP: Record<string, string> = {
	APPOINTMENT_NOT_AVAILABLE: 'slotNotAvailable',
	NO_SUBSCRIBERS: 'noSubscribers',
	MASTER_SERVICE_MAX_IMAGES_COUNT: 'maxImagesCount',
}

const actionErrorsGroupFromPath = (segments: string[]): string => {
	if (segments[0] === 'master' && segments[1] === 'master-service') {
		return 'masterService'
	}

	return kebabToCamel(segments[0])
}

const buildActionErrorsPart = (
	segments: string[],
	content: Messages,
): Messages => {
	const group = actionErrorsGroupFromPath(segments)
	const groupMessages: Messages = {}

	for (const [apiKey, message] of Object.entries(content)) {
		const key =
			ACTION_ERROR_KEY_MAP[apiKey] ??
			kebabToCamel(apiKey.toLowerCase().replace(/_/g, '-'))

		groupMessages[key] = message
	}

	return { actionErrors: { [group]: groupMessages } }
}

export const localeResources = {
${localeBlocks.join('\n')}
} as const

export type GeneratedAppLocale = keyof typeof localeResources
`

	mkdirSync(path.dirname(OUT_FILE), { recursive: true })

	let prev = ''
	try {
		prev = readFileSync(OUT_FILE, 'utf8')
	} catch {}

	if (prev !== content) {
		writeFileSync(OUT_FILE, content)
		console.log(
			`[i18n] generated ${path.relative(ROOT, OUT_FILE)} (${locales.join(', ')})`,
		)
	} else {
		console.log('[i18n] locale-resources.generated.ts up to date')
	}
}

function safeGenerate() {
	try {
		generate()
	} catch (error) {
		console.error('[i18n] generation failed:', error)
		process.exitCode = 1
	}
}

function startWatch() {
	safeGenerate()

	let timer
	const debounced = () => {
		clearTimeout(timer)
		timer = setTimeout(safeGenerate, 150)
	}

	const watcher = watch(
		MESSAGES_DIR,
		{ recursive: true },
		(_event, filename) => {
			if (!filename || filename.endsWith('.json') || !path.extname(filename)) {
				debounced()
			}
		},
	)

	console.log(
		`[i18n] watching ${path.relative(ROOT, MESSAGES_DIR)} for changes...`,
	)

	const stop = () => {
		watcher.close()
		process.exit(0)
	}

	process.on('SIGINT', stop)
	process.on('SIGTERM', stop)
}

if (process.argv.includes('--watch')) {
	startWatch()
} else {
	safeGenerate()
}
